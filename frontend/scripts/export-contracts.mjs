import { readFile, writeFile } from 'node:fs/promises'
import { z } from 'zod'
import { contracts } from '../src/contracts/index.ts'

const target = new URL('../src/contracts/schema.json', import.meta.url)
const workerTarget = new URL('../../agents/fetch-seller/seller.schema.json', import.meta.url)
const schema = {
  $schema: 'https://json-schema.org/draft/2020-12/schema',
  $id: 'urn:converge:contracts:1',
  $comment: 'Generated from index.ts. DRAFT pending Dev S review. Server semantic checks are additional.',
  $defs: Object.fromEntries(Object.entries(contracts).map(([name, contract]) => {
    const { $schema: dialect, ...definition } = z.toJSONSchema(contract, { target: 'draft-2020-12' })
    if (!dialect) throw new Error(`Missing JSON Schema dialect for ${name}`)
    return [name, definition]
  })),
}
const sellerSchema = {
  $schema: schema.$schema,
  $id: 'https://converge.local/contracts/seller.v1.schema.json',
  $comment: 'Request envelopes remain v1; council and final decision envelopes are v2. Generated from the canonical registry.',
  oneOf: ['SellerBrief', 'SellerDecision', 'CouncilJobInput', 'SellerAdvocacy', 'SellerReply', 'SellerFinalDecision', 'SellerFinalJobInput', 'SellerFinalAuthority'].map(name => ({ $ref: `#/$defs/${name}` })),
  $defs: Object.fromEntries(['SellerBrief', 'SellerDecision', 'SellerProposal', 'CouncilJobInput', 'SellerAdvocacy', 'SellerReply', 'SellerFinalDecision', 'SellerFinalJobInput', 'SellerFinalAuthority'].map(name => [name, schema.$defs[name]])),
}
// Agentverse-hosted modules may run without __file__ or uploaded data files, so the
// worker also gets the same generated JSON as a Python module (never hand-edited).
const workerModuleTarget = new URL('../../agents/fetch-seller/seller_schema_data.py', import.meta.url)
const sellerJson = `${JSON.stringify(sellerSchema, null, 2)}\n`
if (sellerJson.includes("'''")) throw new Error('Seller schema cannot be embedded in a raw Python string')
const workerModule = `"""Generated by frontend/scripts/export-contracts.mjs from the canonical contracts. Do not edit."""\n\nSCHEMA_JSON = r'''${sellerJson}'''\n`
for (const [file, value, raw] of [
  [target, schema],
  [new URL('../convex/lib/seller.schema.json', import.meta.url), sellerSchema],
  [workerTarget, sellerSchema],
  [workerModuleTarget, null, workerModule],
]) {
  const content = raw ?? `${JSON.stringify(value, null, 2)}\n`
  if (process.argv.includes('--check')) {
    if (await readFile(file, 'utf8') !== content) throw new Error('Contract export is stale; run npm run contracts:export')
  } else await writeFile(file, content)
}
console.log('Application and seller worker schemas match the canonical runtime contracts.')
